#!/usr/bin/env python3
"""Generate build/generated/tests/elevator.txt: ride the tower elevator (Map 62).
On arrival the doors close, the car shakes while switch 187 is on, two system
message boxes appear (A dismisses them), then the car stops (switch 187 off).
Pressing A at either door must then open it and leave for Map 60."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from scriptgen import Script
root = os.path.join(os.path.dirname(__file__), '..', '..')
s = Script(["GENERATED by tests/gen/gen_elevator.py - tower elevator doors (Map 62)"])
s.boot_to_map()
s.emit("warp 62 19 15 1", 60)
s.emit("expect-map 62")
for _ in range(80):            # ~43 s: let the ride play, dismiss the message boxes
    s.press("A", 20)
s.emit("expect-sw 187 0")
s.emit("print")
s.press("UP", 10)              # face the left door (19,14)
s.press("A", 10)
s.advance(2000)
s.emit("expect-map 60")
s.emit("print")
s.emit("shot elevator_arrived", 2)
os.makedirs(os.path.join(root, 'build/generated/tests'), exist_ok=True)
s.save(os.path.join(root, 'build/generated/tests/elevator.txt'))
