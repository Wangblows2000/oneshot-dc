#!/usr/bin/env python3
"""Generate tests/scripts/debug_menu.txt: hidden Debug Menu unlock + its three pages.
Icon-cursor positions are simulated here (7 icons before unlock, 8 after) because
every D-pad press in the unlock attempts also moves the desktop's icon cursor."""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from scriptgen import Script
root = os.path.join(os.path.dirname(__file__), '..', '..')
idx = json.load(open(os.path.join(root, 'build/generated/debug_index.json')))   # from YOUR data (tools/mkdebug.py)
s = Script(["GENERATED by tests/gen/gen_debug_menu.py - hidden Debug Menu"])
s.boot_to_map()
sel = [0]; nic = [7]
def pad(btn, gap=8):
    s.press(btn, gap)
    if btn == "UP": sel[0] = (sel[0] - 1) % nic[0]
    if btn == "DOWN": sel[0] = (sel[0] + 1) % nic[0]
def hold_lr(frames):
    s.emit("L,R", frames); s.emit("-", 10)

s.comment("desktop opens without the icon")
s.press("START", 30); s.emit("expect-window none"); s.emit("expect-debug 0"); s.emit("shot debug_01_hidden", 2)
s.comment("L+R alone (no sequence)")
hold_lr(60); s.emit("expect-debug 0")
s.comment("partial sequence: Up Up Down, then L+R")
for b in ["UP", "UP", "DOWN"]: pad(b)
hold_lr(60); s.emit("expect-debug 0")
s.comment("wrong order: Up Down Up Down, then L+R")
for b in ["UP", "DOWN", "UP", "DOWN"]: pad(b)
hold_lr(60); s.emit("expect-debug 0")
s.comment("correct directions but another button (Y) before L+R")
for b in ["UP", "UP", "DOWN", "DOWN"]: pad(b)
s.press("Y", 8); hold_lr(60); s.emit("expect-debug 0")
s.comment("correct sequence but L+R only tapped (not held)")
for b in ["UP", "UP", "DOWN", "DOWN"]: pad(b)
hold_lr(6); s.emit("expect-debug 0")
s.comment("correct sequence: Up Up Down Down, hold L+R")
for b in ["UP", "UP", "DOWN", "DOWN"]: pad(b)
s.emit("L,R", 40); s.emit("expect-debug 1"); s.emit("expect-window none")   # still held: no side effects
s.emit("L,R", 30); s.emit("expect-window none"); s.emit("-", 10)
nic[0] = 8
s.emit("shot debug_02_icon_visible", 2)
s.comment("repeat the sequence: nothing new happens (no repeated activation)")
for b in ["UP", "UP", "DOWN", "DOWN"]: pad(b)
hold_lr(40); s.emit("expect-debug 1"); s.emit("expect-window none")
s.comment("open the Debug Menu icon (last icon)")
while sel[0] != 7: pad("DOWN", 6)
s.press("A", 20); s.emit("expect-window Debug_Menu"); s.emit("shot debug_03_rooms", 2)
s.comment("scroll the room list")
for _ in range(14): s.press("DOWN", 4)
s.emit("shot debug_04_rooms_scrolled", 2)
s.press("RIGHT", 6); s.press("LEFT", 6)
s.comment("R: Rooms -> Cutscenes -> Music -> Rooms")
s.press("R", 10); s.emit("shot debug_05_cutscenes", 2)
s.press("R", 10); s.emit("shot debug_06_music", 2)
s.comment("music: play track 0, B stops it and restores the game's music")
s.emit("remember-bgm")                              # the game's own music before the preview
s.press("A", 20); s.emit("expect-bgm-index 0"); s.emit("shot debug_07_music_playing", 2)
s.press("DOWN", 6); s.press("A", 20); s.emit("expect-bgm-index 1")
s.press("B", 10); s.emit("expect-bgm-remembered"); s.emit("expect-window Debug_Menu")
s.comment("music: closing the window also stops it")
s.press("A", 20); s.emit("expect-bgm-index 1")
s.press("B", 10); s.emit("expect-bgm-remembered"); s.press("B", 10); s.emit("expect-window none")
s.comment("room select: livingroom (map 5) via the existing teleport")
s.press("A", 20); s.emit("expect-window Debug_Menu")   # reopens on the Rooms page
rooms = [r['map'] for r in idx['rooms']]
target = rooms.index(5)
for _ in range(target): s.press("DOWN", 4)
s.press("A", 20); s.wait(60); s.advance()
s.emit("expect-map 5"); s.emit("expect-window (desktop_closed)"); s.emit("print"); s.emit("shot debug_08_room_warped", 2)
s.comment("cutscene: the starting room's wake-up scene (map 2) plays, then returns to the Debug Menu with state restored")
s.emit("setvar 50 4242"); s.emit("item 2 1")
cuts = [(c['map'], c['event'], c['page']) for c in idx['cutscenes']]
ci = next(i for i, c in enumerate(idx['cutscenes']) if c['map'] == 2)        # first scene on map 2
s.press("START", 30)
s.press("A", 20); s.press("R", 10)                       # Debug Menu -> Cutscenes
for _ in range(ci): s.press("DOWN", 4)
s.press("A", 10); s.emit("expect-playback 1"); s.wait(70); s.emit("shot debug_09_cutscene_playing", 2)
s.advance(4000)
s.emit("expect-playback 0"); s.emit("expect-window Debug_Menu"); s.emit("status")
s.emit("expect-var 50 4242"); s.emit("expect-item 2 1"); s.emit("shot debug_10_back_in_menu", 2)
s.comment("cutscene with host calls (map 61, ending sequence) - B aborts to the desktop, nothing persisted")
sh = next(i for i, c in enumerate(idx['cutscenes']) if c['map'] == 61)
for _ in range(abs(sh - ci)): s.press("DOWN" if sh > ci else "UP", 4)
s.press("A", 10); s.emit("expect-playback 1"); s.wait(150)
s.emit("shot debug_11_ending_cutscene", 2)
s.press("B", 20); s.emit("expect-playback 0"); s.emit("expect-window none"); s.emit("expect-ending 0")
s.emit("expect-var 50 4242"); s.emit("status")
s.comment("leave the desktop: back in the room the player was in before the cutscenes")
s.press("B", 30); s.wait(40); s.emit("expect-map 5"); s.emit("print")
os.makedirs(os.path.join(root, 'build/generated/tests'), exist_ok=True)
s.save(os.path.join(root, 'build/generated/tests/debug_menu.txt'))
