#!/usr/bin/env python3
"""Generate build/generated/tests/alula.txt: solve the Alula floor-pixel puzzle (Map 28)
by WALKING onto the real floor panels, using the solution the game's own check
event tests and the panel positions from the map - and check that the game marks
it solved (switch 103).  Also writes build/generated/alula_grid.json used by
tests/gen/check_clue.py to compare the clue wallpaper with the floor."""
import json, os, sys
root = os.path.join(os.path.dirname(__file__), '..', '..')
sys.path.insert(0, os.path.join(root, 'tools'))
sys.path.insert(0, os.path.dirname(__file__))
import mkvfs
from scriptgen import Script
game = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'assets/source_readonly/oneshot')
sol, cols, rows, where = mkvfs.find_pixel_solution(game)
assert sol, "puzzle not found"
# panel origin: the solution keys are (col,row) relative to the top-left panel; find it again
import lcf
m = lcf.load_map(os.path.join(game, 'Map0028.lmu'))
xs, ys = [], []
for ev in m.events:
    for pg in ev.pages:
        for c in pg.commands:
            if c.code == 10210 and c.params[1] == c.params[2] and 121 <= c.params[1] <= 150 and pg.trigger == 1:
                xs.append(ev.x); ys.append(ev.y)
x0, y0 = min(xs), min(ys)
os.makedirs(os.path.join(root, 'build/generated/tests'), exist_ok=True)
json.dump(dict(cols=cols, rows=rows, x0=x0, y0=y0, lit=[[c, r] for (c, r), on in sol.items() if on]),
          open(os.path.join(root, 'build/generated/alula_grid.json'), 'w'))
s = Script(["GENERATED by tests/gen/gen_alula.py - Alula floor puzzle walked on the real panels"])
s.boot_to_map()
s.emit("setsw 103 0")
s.emit(f"warp 28 {x0} {y0 - 1} 3", 60); s.advance(); s.emit("print")
def tap(b): s.press(b, 22)
cur = 0
for c in range(cols):
    targets = [r for r in range(rows) if sol[(c, r)]]
    if not targets: continue
    while cur < c: tap("RIGHT"); cur += 1
    for r in targets:
        for _ in range(r + 1): tap("DOWN")
        for _ in range(r + 1): tap("UP")
    s.emit("print")
s.wait(30)
s.emit("expect-sw 103 1")
s.emit("shot alula_solved", 2)
s.save(os.path.join(root, 'build/generated/tests/alula.txt'))
print(f"alula.txt: {cols}x{rows} panels at ({x0},{y0}), {sum(sol.values())} lit")
