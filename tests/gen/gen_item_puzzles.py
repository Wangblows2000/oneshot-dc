#!/usr/bin/env python3
"""Generate tests/scripts/item_puzzles.txt: puzzles that need COMBINED items, played
through the Items menu + action button against the original events:
  1. starting house: bottle of alcohol + dry branch -> wet branch; branch on the TV -> torch;
     torch on the fireplace (Map5 ev4) -> fire lit (sw 11)
  2. mines rowbot (Map18 ev6): lightbulb + empty battery -> charged battery -> rowbot (sw 94);
     bottle of acid + sponge with rubber gloves -> wet sponge -> rowbot (sw 95)
  3. glen gatekeeper (Map37 ev11): feather + ink bottle -> pen -> sign the scroll (sw 114)
Inventory / earlier-story switches are set directly (state injection, marked 'SETUP');
everything after that goes through the real menu, interpreter and event pages.
Checked through items, switches and which event page ran - no game text."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from scriptgen import Script
root = os.path.join(os.path.dirname(__file__), '..', '..')
s = Script(["GENERATED by tests/gen/gen_item_puzzles.py - puzzles that require combined items"])
s.boot_to_map()

def give(*ids):
    s.emit("clear-items"); s.emit("setvar 9 0")
    for i in ids: s.emit(f"item {i} 1")
    s.wait(4)

s.comment("1. starting house: torch for the fireplace")
s.emit("warp 5 18 11", 40); s.advance(); s.press("UP", 10)            # face the TV (Map5 ev8 at 18,10)
give(3, 4)                                               # SETUP: bottle of alcohol (fridge) + dry branch
s.hold_item([3, 4], 3); s.hold_item([3, 4], 4); s.advance()
s.emit("expect-item 5 1"); s.emit("expect-item 11 1")
s.hold_item([5, 11], 5)                                  # hold the wet branch
s.emit("expect-var 9 5")
s.press("A", 20); s.advance()
s.emit("expect-page 8 3"); s.emit("expect-item 6 1"); s.emit("expect-item 5 0")
s.emit("shot puzzle_01_torch")
s.emit("warp 5 26 11", 40); s.advance(); s.press("UP", 10)            # fireplace (ev4 at 26,10), facing up
s.hold_item([6, 11], 6); s.press("A", 20); s.advance()
s.emit("expect-sw 11 1"); s.emit("expect-item 6 0")
s.press("A", 20); s.advance()
s.emit("expect-page 4 3"); s.emit("shot puzzle_02_fire_lit", 4)

s.comment("2. rowbot: charged battery, then wet sponge (needs rubber gloves)")
s.emit("warp 18 30 48", 40); s.advance(); s.press("UP", 10)           # rowbot (Map18 ev6 at 30,47)
give(1, 13)                                              # SETUP: lightbulb + empty battery
s.hold_item([1, 13], 1); s.hold_item([1, 13], 13); s.advance()
s.emit("expect-item 14 1")
s.hold_item([1, 14], 14); s.press("A", 20); s.advance()
s.emit("expect-sw 94 1"); s.emit("expect-item 14 0")
give(16, 20); s.emit("equip 1 2 99")                     # SETUP: bottle of acid + sponge, gloves worn
s.hold_item([16, 20], 16); s.hold_item([16, 20], 20); s.advance()
s.emit("expect-item 17 1")
s.hold_item([17], 17); s.press("A", 20); s.advance()
s.emit("expect-sw 95 1"); s.emit("expect-item 17 0"); s.emit("shot puzzle_03_rowbot", 4)

s.comment("3. gatekeeper: pen")
s.emit("setsw 113 1")                                    # SETUP: already asked for a pen
s.emit("warp 37 34 96", 40); s.advance(); s.press("UP", 10)           # gatekeeper (Map37 ev11 at 34,95)
give(25, 26)                                             # SETUP: feather + ink bottle
s.hold_item([25, 26], 25); s.hold_item([25, 26], 26); s.advance()
s.emit("expect-item 30 1")
s.hold_item([30], 30); s.press("A", 20)
s.wait(30); s.emit("shot puzzle_04_pen", 2); s.advance()
s.emit("expect-page 11 3"); s.emit("expect-sw 114 1"); s.emit("expect-item 30 0")
s.emit("print")
os.makedirs(os.path.join(root, 'build/generated/tests'), exist_ok=True)
s.save(os.path.join(root, 'build/generated/tests/item_puzzles.txt'))
