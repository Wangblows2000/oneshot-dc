#!/usr/bin/env python3
"""Generate tests/scripts/combinations.txt: every combination in CE20 "use ITEM",
driven through the real Items menu (hold one item, then select the other).
Item ids/expectations come from build/generated/item_inventory.json (made from YOUR
copy of the game by tools/item_inventory.py), so the script is generated locally
under build/ and contains no game text: results are checked through the inventory,
variable 9 and whether CE32 ("can't combine") ran."""
import json, os, sys
root = os.path.join(os.path.dirname(__file__), '..', '..')
inv = json.load(open(os.path.join(root, 'build/generated/item_inventory.json')))
recipes = inv['recipes']
out = ["# GENERATED by tests/gen/gen_combinations.py - item combinations through the Items menu.",
       "# Each case: clear inventory, give two items, select item 1 (held), select item 2 (combine)."]
t = 0
def emit(s):
    out.append(f"{t} {s}")
def step(s, gap=10):
    global t; emit(s); t += 2; emit("-"); t += gap
def select(index):
    step("B", 14); step("A", 12)
    for _ in range(index): step("DOWN", 6)
    step("A", 20)
emit("-"); t += 30; step("A", 128); t = 200; emit("advance 3000"); t += 10
emit("warp 2 22 19"); t += 40
def case(name, a, b, order, expect_items, refused=None, equip=None):
    global t
    out.append(f"# --- {name}")
    emit("reset-ce 32")
    emit("clear-items"); emit("setvar 9 0")
    emit(f"equip 1 2 {equip or 0}")
    emit(f"item {a} 1"); emit(f"item {b} 1"); t += 4
    ids = sorted([a, b])
    first, second = order
    select(ids.index(first)); emit(f"expect-var 9 {first}"); t += 4
    select(ids.index(second)); t += 4
    emit("advance 3000"); t += 6
    for iid, n in expect_items.items(): emit(f"expect-item {iid} {n}"); t += 1
    emit("expect-var 9 0"); emit("expect-sw 119 0"); t += 1
    if refused is not None: emit(f"expect-ce 32 {1 if refused else 0}"); t += 1
    t += 10
for r in recipes:
    a, b = r['a'], r['b']
    exp = {a: 1, b: 1}
    for i in r['removes']: exp[i] = 0
    for i in r['adds']: exp[i] = 1
    name = f"recipe: item {a} + item {b}"
    if r['needs_equipped']:
        # without the required equipment: nothing changes (its own refusal, not CE32)
        case(name + " (equipment missing)", a, b, (a, b), {a: 1, b: 1}, False)
        case(name + f" (item {r['needs_equipped'][0]} equipped)", a, b, (a, b), exp, False, equip=r['needs_equipped'][0])
    else:
        case(name, a, b, (a, b), exp, False)
# reverse selection order gives the same result (CE20 sorts the pair)
r0 = next(r for r in recipes if r['adds'])
exp = {r0['a']: 1, r0['b']: 1}
for i in r0['removes']: exp[i] = 0
for i in r0['adds']: exp[i] = 1
case("reverse order", r0['a'], r0['b'], (r0['b'], r0['a']), exp)
# invalid pair: TV remote + lightbulb (no recipe) -> CE32 refusal, inventory unchanged
case("invalid pair: items 1 + 2 (no recipe)", 1, 2, (2, 1), {1: 1, 2: 1}, True)
os.makedirs(os.path.join(root, 'build/generated/tests'), exist_ok=True)
open(os.path.join(root, 'build/generated/tests/combinations.txt'), 'w').write('\n'.join(out) + '\n')
print("combinations.txt:", t + 200, "frames")
